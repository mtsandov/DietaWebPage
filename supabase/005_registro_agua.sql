-- Registro de consumo de agua (cada fila es una toma en ml).
-- Ejecutar una vez en Supabase > SQL Editor.
CREATE TABLE IF NOT EXISTS registro_agua (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL DEFAULT auth.uid(),
  fecha DATE NOT NULL,
  ml FLOAT4 NOT NULL CHECK (ml > 0),
  created_at TIMESTAMPTZ DEFAULT now()
);

ALTER TABLE registro_agua ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Control total sobre registro de agua propio" ON registro_agua;
CREATE POLICY "Control total sobre registro de agua propio"
ON registro_agua FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

CREATE INDEX IF NOT EXISTS registro_agua_user_fecha_idx ON registro_agua (user_id, fecha);

GRANT SELECT, INSERT, UPDATE, DELETE ON registro_agua TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;
REVOKE ALL ON registro_agua FROM anon;
